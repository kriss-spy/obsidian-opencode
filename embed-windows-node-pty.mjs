import fs from "node:fs";
import path from "node:path";
import { gzipSync } from "node:zlib";

// Pin node-pty in package.json/lockfile. Ship its maintained ConPTY distribution,
// including its license, rather than linking to the older OS console host.
const root = "node_modules/node-pty";
if (JSON.parse(fs.readFileSync(`${root}/package.json`, "utf8")).version !== "1.1.0") {
	throw new Error("Expected node-pty 1.1.0");
}
for (const arch of ["x64", "arm64"]) {
	const files = {};
	function add(relative) { files[relative] = fs.readFileSync(path.join(root, relative)).toString("base64"); }
	function javascript(directory) {
		for (const entry of fs.readdirSync(path.join(root, directory), { withFileTypes: true })) {
			const relative = `${directory}/${entry.name}`;
			if (entry.isDirectory()) javascript(relative);
			else if (entry.name.endsWith(".js") && !entry.name.endsWith(".test.js")) add(relative);
		}
	}
	javascript("lib");
	add("LICENSE");
	const native = `prebuilds/win32-${arch}`;
	for (const name of ["conpty.node", "conpty_console_list.node", "conpty/conpty.dll", "conpty/OpenConsole.exe"]) add(`${native}/${name}`);
	const data = gzipSync(JSON.stringify(files), { level: 9 }).toString("base64");
	fs.writeFileSync(`src/pty/windowsNodePty${arch === "x64" ? "X64" : "Arm64"}.ts`,
		`// Generated by embed-windows-node-pty.mjs from node-pty 1.1.0 (MIT).\n// The archive includes node-pty/LICENSE and unmodified distribution files.\nexport const WINDOWS_NODE_PTY_${arch.toUpperCase()} = "${data}";\n`);
}
