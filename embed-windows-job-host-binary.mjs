import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";

const output = process.argv[3] ?? "src/pty/windowsPtyJobHost.ts";
let input = process.argv[2];
let buildDirectory;

try {
	if (!input) {
		if (process.platform !== "win32") throw new Error("The Windows PTY job host must be compiled on Windows.");
		buildDirectory = fs.mkdtempSync(path.join(os.tmpdir(), "obsidian-opencode-job-build-"));
		input = path.join(buildDirectory, "windows-pty-job-host.exe");
		const compiler = path.join(process.env.WINDIR ?? "C:\\Windows", "Microsoft.NET", "Framework64", "v4.0.30319", "csc.exe");
		execFileSync(compiler, [
			"/nologo",
			"/target:exe",
			"/platform:anycpu",
			"/optimize+",
			`/out:${input}`,
			path.resolve("native/windows-pty-job-host.cs"),
		], { stdio: "inherit" });
	}

	const base64 = fs.readFileSync(input).toString("base64");
	fs.writeFileSync(output, `// Generated by embed-windows-job-host-binary.mjs.\nexport const WINDOWS_PTY_JOB_HOST_BASE64 = "${base64}";\n`);
} finally {
	if (buildDirectory) fs.rmSync(buildDirectory, { recursive: true, force: true });
}
